import argparse
import re
import sys
from pathlib import Path

import sympy as sp


# ---------------------------------------------------------------------------
# Spacetimes: one function per metric. Each returns (coords, g).
# ---------------------------------------------------------------------------

def schwarzschild():
    """Schwarzschild metric, signature (-,+,+,+), M = 1."""
    t, r, theta, phi = sp.symbols('t r theta phi', real=True)
    coords = [t, r, theta, phi]

    f = 1 - 2 / r
    g = sp.diag(-f, 1 / f, r**2, r**2 * sp.sin(theta)**2)
    return coords, g


# Add new spacetimes here, then register them below.
METRICS = {
    'schwarzschild': schwarzschild,
}


# ---------------------------------------------------------------------------
# Processing: 
# ---------------------------------------------------------------------------

def inverse_and_derivatives(coords, g):
    """Return the inverse metric and its derivatives.

    ginv  : 4x4 matrix, g^{mu nu}
    dginv : list of 4 matrices, dginv[a][mu, nu] = d(g^{mu nu}) / d(x^a)
    """
    ginv = g.inv()
    ginv = ginv.applyfunc(sp.simplify)
    dginv = [ginv.diff(c).applyfunc(sp.simplify) for c in coords]
    return ginv, dginv


def print_report(coords, ginv, dginv):
    """Print the inverse metric and the non-zero derivatives."""
    print('Inverse metric:')
    sp.pprint(ginv)
    print()
    print('Non-zero derivatives of the inverse metric:')
    for a in range(4):
        for mu in range(4):
            for nu in range(mu, 4):
                d = dginv[a][mu, nu]
                if d != 0:
                    print(f'd/d{coords[a]} g^({mu},{nu}) =', d)


# ---------------------------------------------------------------------------
# Fortran output
# ---------------------------------------------------------------------------

def to_fortran(expr):
    """Convert a sympy expression to a Fortran expression string."""
    text = sp.fcode(expr, source_format='free', standard=95)
    # sympy writes literals like 2.0d0; use the kind parameter instead
    return re.sub(r'(\d+\.\d*)d0', r'\1_wp', text)


def generate_fortran(name, coords, ginv, dginv):
    """Build the text of the Fortran module for one spacetime."""
    # 1. collect every non-zero entry together with its Fortran target
    entries = []   # (target text, expression)
    for mu in range(4):
        for nu in range(mu, 4):
            if ginv[mu, nu] != 0:
                entries.append((f'ginv({mu + 1},{nu + 1})', ginv[mu, nu]))
                if mu != nu:
                    entries.append((f'ginv({nu + 1},{mu + 1})', ginv[mu, nu]))
    for a in range(4):
        for mu in range(4):
            for nu in range(mu, 4):
                if dginv[a][mu, nu] != 0:
                    entries.append((f'dginv({a + 1},{mu + 1},{nu + 1})', dginv[a][mu, nu]))
                    if mu != nu:
                        entries.append((f'dginv({a + 1},{nu + 1},{mu + 1})', dginv[a][mu, nu]))

    # 2. common subexpression elimination: shared parts are computed once
    exprs = [e for _, e in entries]
    temps, reduced = sp.cse(exprs, symbols=sp.numbered_symbols('c'))

    # 3. which coordinates are really used?
    used = set()
    for _, e in temps:
        used |= e.free_symbols
    for e in reduced:
        used |= e.free_symbols
    used_coords = [(i, c) for i, c in enumerate(coords) if c in used]

    lines = []
    lines.append('! AUTO-GENERATED by tools/gen_metric.py -- DO NOT EDIT.')
    lines.append(f'! Metric: {name}. Regenerate with: python tools/gen_metric.py {name}')
    lines.append('!')
    lines.append('! x(1:4)        coordinates (t, r, theta, phi)')
    lines.append('! ginv(mu,nu)     inverse metric g^{mu nu}')
    lines.append('! dginv(a,mu,nu)  derivative d g^{mu nu} / d x^a')
    lines.append('module metric')
    lines.append('  implicit none')
    lines.append('  private')
    lines.append('  public :: wp, metric_inv')
    lines.append('')
    lines.append('  integer, parameter :: wp = kind(1.0d0)')
    lines.append('')
    lines.append('contains')
    lines.append('')
    lines.append('  attributes(host,device) subroutine metric_inv(x, ginv, dginv)')
    lines.append('    real(wp), intent(in)  :: x(4)')
    lines.append('    real(wp), intent(out) :: ginv(4,4)')
    lines.append('    real(wp), intent(out) :: dginv(4,4,4)')
    names = [str(c) for _, c in used_coords] + [str(s) for s, _ in temps]
    if names:
        lines.append('    real(wp) :: ' + ', '.join(names))
    lines.append('')
    for i, c in used_coords:
        lines.append(f'    {c} = x({i + 1})')
    if used_coords:
        lines.append('')
    lines.append('    ginv  = 0.0_wp')
    lines.append('    dginv = 0.0_wp')
    lines.append('')
    for sym, e in temps:
        lines.append(f'    {sym} = {to_fortran(e)}')
    if temps:
        lines.append('')
    for (target, _), e in zip(entries, reduced):
        lines.append(f'    {target} = {to_fortran(e)}')
    lines.append('  end subroutine metric_inv')
    lines.append('')
    lines.append('end module metric')
    return '\n'.join(lines) + '\n'


# ---------------------------------------------------------------------------
# Entry point: to choose the spacetime
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description='Generate the Fortran metric module.')
    parser.add_argument('name', nargs='?', default='schwarzschild',help=f'spacetime, one of: {", ".join(METRICS)}')
    parser.add_argument('--report', action='store_true',help='print the inverse metric and derivatives')
    parser.add_argument('--out', default=None,help='output file (default: src/generated/metric.f90)')
    args = parser.parse_args()

    if args.name not in METRICS:
        print(f'Unknown metric "{args.name}". Available: {", ".join(METRICS)}')
        sys.exit(1)

    coords, g = METRICS[args.name]()
    assert g.shape == (4, 4)
    ginv, dginv = inverse_and_derivatives(coords, g)

    if args.report:
        print_report(coords, ginv, dginv)

    if args.out:
        out = Path(args.out)
    else:
        out = Path(__file__).resolve().parent.parent / 'src' / 'generated' / 'metric.f90'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(generate_fortran(args.name, coords, ginv, dginv))
    print(f'Wrote {out}')


if __name__ == '__main__':
    main()